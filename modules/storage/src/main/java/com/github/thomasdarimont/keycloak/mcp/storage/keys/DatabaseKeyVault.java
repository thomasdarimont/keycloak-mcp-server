package com.github.thomasdarimont.keycloak.mcp.storage.keys;

import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.security.spec.PKCS8EncodedKeySpec;
import java.security.spec.X509EncodedKeySpec;
import java.util.Base64;
import java.util.List;
import java.util.Optional;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import jakarta.transaction.Transactional;

import org.jboss.logging.Logger;

import com.github.thomasdarimont.keycloak.mcp.config.McpServerConfig;
import com.github.thomasdarimont.keycloak.mcp.keycloak.DefaultSigningKeyGenerator;
import com.github.thomasdarimont.keycloak.mcp.keycloak.KeyVault;
import com.github.thomasdarimont.keycloak.mcp.keycloak.SigningKey;
import com.github.thomasdarimont.keycloak.mcp.keycloak.SigningKeyGenerator;
import com.github.thomasdarimont.keycloak.mcp.spi.ConfigProperty;
import com.github.thomasdarimont.keycloak.mcp.spi.ConfigSpec;
import com.github.thomasdarimont.keycloak.mcp.spi.ProviderConfig;
import com.github.thomasdarimont.keycloak.mcp.storage.StorageEnabledInterceptorFactory;
import com.github.thomasdarimont.keycloak.mcp.storage.crypto.StorageCrypto;

import io.quarkus.arc.lookup.LookupIfProperty;
import io.quarkus.panache.common.Sort;

/**
 * The {@link KeyVault} of the database: {@code private_key_jwt} key pairs in
 * {@code kc_mcp_signing_key}, created on a system's first use and rotated with
 * {@link #createSigningKey} (the previous key keeps its row with {@code retired_at} and
 * stays in the JWKS for {@code kc-mcp.spi.key-vault.db.retired-key-grace-seconds}, an
 * hour by default, so other instances of the server still signing with it are accepted),
 * and raw secrets in {@code kc_mcp_secret}, stored and removed through the admin API
 * ({@link #putSecret}, {@link #deleteSecret}). Private keys and secrets are encrypted at
 * rest when {@code kc-mcp.storage.secret-key} is set. Keys are generated by the
 * {@link SigningKeyGenerator} the server hands over, for {@code kc-mcp.jwt.algorithm}.
 * Replaces the read-only file vault when {@code kc-mcp.storage.enabled=true}; switch it
 * off alone with {@code kc-mcp.spi.key-vault.db.enabled=false}.
 * <p>
 * Two replicas creating the first key of the same system at the same moment both succeed;
 * {@link #findSigningKey} then serves the newer one and the older stays unused.
 */
@ApplicationScoped
@LookupIfProperty(name = StorageEnabledInterceptorFactory.ENABLED, stringValue = "true")
public class DatabaseKeyVault implements KeyVault {

    public static final String ID = "db";

    /** How long a retired key stays in the JWKS, seconds. */
    public static final ConfigProperty RETIRED_KEY_GRACE_SECONDS = ConfigProperty.integer("retired-key-grace-seconds")
        .withDefault("3600");

    public static final ConfigSpec CONFIG_SPEC = ConfigSpec.of(RETIRED_KEY_GRACE_SECONDS);

    private static final Logger LOG = Logger.getLogger(DatabaseKeyVault.class);

    private final StorageCrypto crypto;
    private final McpServerConfig serverConfig;
    /** Set by {@link #configure}; the default until then. */
    private long retiredKeyGraceMillis = Long.parseLong(RETIRED_KEY_GRACE_SECONDS.defaultValue()) * 1000L;
    private volatile SigningKeyGenerator generator;

    @Inject
    public DatabaseKeyVault(StorageCrypto crypto, McpServerConfig serverConfig) {
        this.crypto = crypto;
        this.serverConfig = serverConfig;
        this.generator = new DefaultSigningKeyGenerator(serverConfig.jwt().keySize());
    }

    /** With this grace instead of the configured one, for tests. */
    public DatabaseKeyVault(StorageCrypto crypto, McpServerConfig serverConfig, int retiredKeyGraceSeconds) {
        this(crypto, serverConfig);
        this.retiredKeyGraceMillis = Math.max(0, retiredKeyGraceSeconds) * 1000L;
    }

    @Override
    public void configure(ProviderConfig config) {
        this.retiredKeyGraceMillis = Math.max(0, config.readInt(RETIRED_KEY_GRACE_SECONDS)) * 1000L;
    }

    @Override
    public String id() {
        return ID;
    }

    @Override
    public ConfigSpec configSpec() {
        return CONFIG_SPEC;
    }

    @Override
    public String displayName() {
        return "Database key vault";
    }

    @Override
    public String description() {
        return "private_key_jwt keys and secrets in the database"
                + (crypto.enabled() ? ", encrypted at rest" : ", not encrypted (set kc-mcp.storage.secret-key)");
    }

    @Override
    @Transactional
    public Optional<SigningKey> findSigningKey(String system) {
        return current(system).map(this::toSigningKey);
    }

    /** The current key first, then the keys retired within the grace period. */
    @Override
    @Transactional
    public List<SigningKey> publishedSigningKeys(String system) {
        long since = System.currentTimeMillis() - retiredKeyGraceMillis;
        return SigningKeyEntity
            .<SigningKeyEntity>list("system = ?1 and (retiredAt is null or retiredAt > ?2) order by createdAt desc",
                    system, since)
            .stream()
            .map(this::toSigningKey)
            .toList();
    }

    @Override
    public boolean supportsKeyCreation() {
        return true;
    }

    @Override
    @Transactional
    public int deleteSigningKeys(String system) {
        return (int) SigningKeyEntity.delete("system = ?1", system);
    }

    @Override
    @Transactional
    public SigningKey createSigningKey(String system) {
        String algorithm = serverConfig.jwt().algorithm();
        SigningKey generated = generator.generate(algorithm);
        long now = System.currentTimeMillis();
        List<SigningKeyEntity> active = SigningKeyEntity.list("system = ?1 and retiredAt is null", system);
        for (SigningKeyEntity previous : active) {
            previous.retiredAt = now;
        }
        SigningKeyEntity e = new SigningKeyEntity();
        e.system = system;
        e.kid = generated.keyId();
        e.algorithm = generated.algorithm();
        e.keyType = generated.privateKey().getAlgorithm();
        e.privateKey = crypto.protect(Base64.getEncoder().encodeToString(generated.privateKey().getEncoded()));
        e.publicKey = Base64.getEncoder().encodeToString(generated.publicKey().getEncoded());
        e.createdAt = now;
        e.persist();
        LOG.infof("[%s] %s private_key_jwt key %s in the database", system, generated.algorithm(),
                active.isEmpty() ? "created" : "rotated");
        return generated;
    }

    @Override
    public void useSigningKeyGenerator(SigningKeyGenerator generator) {
        if (generator != null) {
            this.generator = generator;
        }
    }

    /** All keys of a system, newest first, retired ones included. */
    @Transactional
    public List<SigningKeyEntity> history(String system) {
        return SigningKeyEntity.list("system = ?1 order by createdAt desc", system);
    }

    @Override
    @Transactional
    public Optional<String> findSecret(String name) {
        return SecretEntity.<SecretEntity>findByIdOptional(name)
            .map(e -> crypto.reveal(e.value))
            .filter(v -> !v.isBlank());
    }

    @Override
    @Transactional
    public List<String> secretNames() {
        return SecretEntity.<SecretEntity>listAll(Sort.ascending("name")).stream().map(e -> e.name).toList();
    }

    @Override
    public boolean supportsSecretStorage() {
        return true;
    }

    /** Adds or replaces a secret. */
    @Override
    @Transactional
    public void putSecret(String name, String value) {
        long now = System.currentTimeMillis();
        SecretEntity e = SecretEntity.findById(name);
        if (e == null) {
            e = new SecretEntity();
            e.name = name;
            e.createdAt = now;
        }
        e.value = crypto.protect(value);
        e.updatedAt = now;
        e.persist();
    }

    /** Removes a secret; false when unknown. */
    @Override
    @Transactional
    public boolean deleteSecret(String name) {
        return SecretEntity.deleteById(name);
    }

    private static Optional<SigningKeyEntity> current(String system) {
        return SigningKeyEntity
            .<SigningKeyEntity>find("system = ?1 and retiredAt is null order by createdAt desc", system)
            .firstResultOptional();
    }

    SigningKey toSigningKey(SigningKeyEntity e) {
        try {
            KeyFactory factory = KeyFactory.getInstance(e.keyType);
            PrivateKey priv = factory
                .generatePrivate(new PKCS8EncodedKeySpec(Base64.getDecoder().decode(crypto.reveal(e.privateKey))));
            PublicKey pub = factory.generatePublic(new X509EncodedKeySpec(Base64.getDecoder().decode(e.publicKey)));
            return new SigningKey(priv, pub, e.algorithm, e.kid);
        }
        catch (GeneralSecurityException ex) {
            throw new IllegalStateException(
                    "Cannot read the stored signing key of '" + e.system + "': " + ex.getMessage(), ex);
        }
    }
}
